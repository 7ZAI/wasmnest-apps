//! pairing 域（自 bedcode `pairing` 域按域搬迁 · issue #6）
//!
//! 本域是配对语义在**认证中心**侧的落点，按票搬入：
//!
//! - 票「trust/policy/keys」：入场凭证密码学（[`jwt`]）+ 签发密钥环（[`keys`]）+
//!   门面 [`token`]。
//! - 票「pairing/consent」（本票）：6 位配对码状态机与 QR token 状态机
//!   （[`code`] / [`qr`]）。二者**不依赖认证记录库**，故可与上一票并行落地。
//!
//! ## 为什么先搬这几块
//!
//! 六域里只有它们**不依赖认证记录库**：验签/签发/配对码/QR 的输入是 token、密钥环
//! 或时间，输出是 claims / 数字码 / 随机 token。于是它们可以独立落地、独立用
//! **原封不动的既有用例**做行为等价验证（wire 冻结向量 + RFC 7515 官方向量 +
//! TTL 决策表 + 一次性消费矩阵），不必等数据库搬迁。
//!
//! ## 与 bedcode 的关系（搬迁已完成）
//!
//! 注册切换（issue #6 切换票）已落地：本插件注册为认证中心，bedcode 去注册并把
//! 设备中心 / consent / 连接记录改经互调消费。bedcode 侧仍留有六域副本（旧 api
//! 面兼容），随后续「删除六域副本」票整体移除；在此之前两份实现**不得单独演进**
//! ——它们的行为由同一组测试与同一个 wire 冻结向量钉住。
//!
//! ## 待搬（后续票）
//!
//! - `auth_http::biometric`（生物凭证挑战 + P-256 验签）：**依赖认证记录库**
//!   （公钥行 / 配对活跃判定），随 `auth_records` 票一起搬。
//! - `auth_records`（信任记录真源）、注册切换（K4）。

